/**
 * Overleaf-Ready ATS LaTeX Generator
 * Uses standard pdflatex packages installed out-of-the-box on Overleaf.
 */

const LATEX_ESCAPE_MAP = {
  "\\": "\\textbackslash{}",
  "&": "\\&",
  "%": "\\%",
  "$": "\\$",
  "#": "\\#",
  "_": "\\_",
  "{": "\\{",
  "}": "\\}",
  "~": "\\textasciitilde{}",
  "^": "\\textasciicircum{}",
  "–": "--",
  "—": "--",
  "‘": "'",
  "’": "'",
  "“": "\"",
  "”": "\""
};

export function escapeLatex(input) {
  if (input === null || input === undefined) return "";
  return String(input).replace(/[\\&%$#_{}~^–—‘’“”]/g, (ch) => LATEX_ESCAPE_MAP[ch] || ch);
}

export function sanitizeFilename(name) {
  return (name || "Resume")
    .replace(/[^a-zA-Z0-9_-]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 60);
}

export function generateOverleafLatex(resume, options = {}) {
  const template = options.template === "modern-teal" ? "modern-teal" : "ats-classic";
  const accentHex = template === "modern-teal" ? "0F766E" : "111827";
  const linkHex = template === "modern-teal" ? "0E7490" : "1D4ED8";

  const basics = resume.basics || {};
  const skills = resume.skillCategories || [];
  const experiences = resume.experiences || [];
  const projects = resume.projects || [];
  const education = resume.education || [];

  const phoneHref = (basics.phone || "").replace(/[^+\d]/g, "");
  const linkedinHref = basics.linkedin || "https://www.linkedin.com/in/parth-lunagaria";
  const linkedinLabel = basics.linkedinLabel || linkedinHref.replace(/^https?:\/\/(www\.)?/, "");

  const skillRows = skills
    .filter((cat) => (cat.skills || []).length > 0)
    .map(
      (cat) =>
        `  \\textbf{${escapeLatex(cat.title)}}: ${cat.skills.map((s) => escapeLatex(s)).join(", ")}`
    )
    .join(" \\\\\n");

  const experienceBlocks = experiences
    .map((exp) => {
      const bullets = (exp.bullets || [])
        .filter((b) => b && b.trim())
        .map((b) => `    \\resumeItem{${escapeLatex(b.trim())}}`)
        .join("\n");
      return `\\resumeSubheading
  {${escapeLatex(exp.role)}}{${escapeLatex(exp.duration)}}
  {${escapeLatex(exp.company)}}{${escapeLatex(exp.location)}}
  \\resumeItemListStart
${bullets}
  \\resumeItemListEnd`;
    })
    .join("\n\n");

  const projectBlocks = projects
    .map((proj) => {
      const bullets = (proj.bullets || [])
        .filter((b) => b && b.trim())
        .map((b) => `    \\resumeItem{${escapeLatex(b.trim())}}`)
        .join("\n");
      const titleLine = `\\textbf{${escapeLatex(proj.title)}} $|$ \\emph{${escapeLatex(proj.platform || "")}}`;
      return `\\resumeProjectHeading
  {${titleLine}}{${escapeLatex(proj.tagline || "")}}
  \\resumeItemListStart
${bullets}
  \\resumeItemListEnd`;
    })
    .join("\n\n");

  const educationBlocks = education
    .map(
      (edu) => `\\resumeSubheading
  {${escapeLatex(edu.institution)}}{${escapeLatex(edu.duration)}}
  {${escapeLatex(edu.degree)}}{${escapeLatex(edu.location)}}`
    )
    .join("\n");

  const languagesLine =
    Array.isArray(basics.languages) && basics.languages.length > 0
      ? `  \\textbf{Languages}: ${basics.languages.map((l) => escapeLatex(l)).join(", ")}`
      : "";

  return `%-------------------------
% Overleaf-Ready ATS Resume
% Generated by RN Resume Studio for ${escapeLatex(basics.name || "Parth Lunagaria")}
% Compiler: pdfLaTeX (Standard Overleaf Default)
%------------------------

\\documentclass[letterpaper,10.5pt]{article}

\\usepackage[empty]{fullpage}
\\usepackage{titlesec}
\\usepackage[usenames,dvipsnames]{xcolor}
\\usepackage{enumitem}
\\usepackage[hidelinks]{hyperref}
\\usepackage{tabularx}
\\usepackage[T1]{fontenc}
\\usepackage{lmodern}
\\input{glyphtounicode}

% Color palette
\\definecolor{accentColor}{HTML}{${accentHex}}
\\definecolor{linkColor}{HTML}{${linkHex}}

\\hypersetup{
  colorlinks=true,
  urlcolor=linkColor,
  linkcolor=linkColor
}

% Margins
\\addtolength{\\oddsidemargin}{-0.55in}
\\addtolength{\\evensidemargin}{-0.55in}
\\addtolength{\\textwidth}{1.1in}
\\addtolength{\\topmargin}{-0.6in}
\\addtolength{\\textheight}{1.2in}

\\urlstyle{same}
\\raggedbottom
\\raggedright
\\setlength{\\tabcolsep}{0in}

% Section formatting
\\titleformat{\\section}{
  \\vspace{-5pt}\\scshape\\raggedright\\large\\bfseries\\color{accentColor}
}{}{0em}{}[\\color{accentColor}\\titlerule \\vspace{-5pt}]

% Ensure ATS PDF text extraction works cleanly
\\pdfgentounicode=1

% Custom commands
\\newcommand{\\resumeItem}[1]{
  \\item\\small{
    {#1 \\vspace{-2pt}}
  }
}

\\newcommand{\\resumeSubheading}[4]{
  \\vspace{-1pt}\\item
    \\begin{tabular*}{0.99\\textwidth}[t]{l@{\\extracolsep{\\fill}}r}
      \\textbf{#1} & \\small #2 \\\\
      \\textit{\\small#3} & \\textit{\\small #4} \\\\
    \\end{tabular*}\\vspace{-6pt}
}

\\newcommand{\\resumeProjectHeading}[2]{
  \\item
    \\begin{tabular*}{0.99\\textwidth}{l@{\\extracolsep{\\fill}}r}
      \\small#1 & \\textit{\\small #2} \\\\
    \\end{tabular*}\\vspace{-6pt}
}

\\newcommand{\\resumeSubHeadingListStart}{\\begin{itemize}[leftmargin=0.0in, label={}]}
\\newcommand{\\resumeSubHeadingListEnd}{\\end{itemize}}
\\newcommand{\\resumeItemListStart}{\\begin{itemize}[leftmargin=0.16in]}
\\newcommand{\\resumeItemListEnd}{\\end{itemize}\\vspace{-4pt}}

\\begin{document}

%----------HEADER----------
\\begin{center}
  {\\Huge \\scshape \\textbf{\\color{accentColor}${escapeLatex(basics.name || "Parth Lunagaria")}}} \\\\ \\vspace{3pt}
  {\\small \\textbf{${escapeLatex(basics.headline || "Senior Software Engineer")}}} \\\\ \\vspace{3pt}
  \\small
  ${escapeLatex(basics.location || "")} $|$
  \\href{tel:${phoneHref}}{${escapeLatex(basics.phone || "")}} $|$
  \\href{mailto:${basics.email || ""}}{${escapeLatex(basics.email || "")}} $|$
  \\href{${linkedinHref}}{${escapeLatex(linkedinLabel)}}
\\end{center}
\\vspace{-10pt}

%----------PROFESSIONAL SUMMARY----------
\\section{Professional Summary}
\\small{${escapeLatex(basics.summary || "")}}
\\vspace{-4pt}

%----------TECHNICAL SKILLS----------
\\section{Technical Skills}
\\begin{itemize}[leftmargin=0.0in, label={}]
  \\small{\\item{
${skillRows}
  }}
\\end{itemize}
\\vspace{-10pt}

%----------WORK EXPERIENCE----------
\\section{Work Experience}
\\resumeSubHeadingListStart
${experienceBlocks}
\\resumeSubHeadingListEnd
\\vspace{-6pt}

%----------FEATURED PROJECTS----------
\\section{Key Projects}
\\resumeSubHeadingListStart
${projectBlocks}
\\resumeSubHeadingListEnd
\\vspace{-6pt}

%----------EDUCATION----------
\\section{Education}
\\resumeSubHeadingListStart
${educationBlocks}
\\resumeSubHeadingListEnd
${languagesLine ? `\\vspace{-6pt}\n\\small{\\noindent${languagesLine.trim()}}` : ""}

\\end{document}
`;
}
